"""SI table of the Rocklin finite-size corrections for the four +1 ligands, and text macros.
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from pairwise_ddg import CALC, EXP, PDB

HERE = Path(__file__).resolve().parent
# The O-centred TIP7P DSC (corrected_dg_v2_main.tsv: DSC_O_approx) is an unvalidated parameter scenario
# (Codex review 2026-10-09); it is not shown in Table S10 and never enters a corrected comparison.
SHOW_TIP7P_O_APPROX = False
C = HERE / "charge_correction"
cor = pd.read_csv(C / "corrected_dg_v2_main.tsv", sep="\t")
num = lambda x: "--" if pd.isna(x) else (f"\\ensuremath{{{x:+.2f}}}" if True else "")
rows = []
for model in ("TIP3P", "TIP4P", "TIP5P", "TIP7P"):
    rows.append(r"\multicolumn{9}{l}{\textit{" + model + r"}} \\")
    for _, r in cor[cor.model == model].iterrows():
        if model == "TIP7P" and SHOW_TIP7P_O_APPROX:   # off: unvalidated scenario, kept only in the audit table
            ap = lambda x: f"({num(x)})"
            rows.append(" & ".join([r.pdb, num(r.NET_USV), num(r.RIP), num(r.EMP), ap(r.DSC_O_approx),
                                    ap(r.correction_O_approx), "--", f"\\ensuremath{{{r.dG_uncorrected:.2f}}}",
                                    ap(r.dG_O_approx).replace("+", "")]) + r" \\")
            continue
        rows.append(" & ".join([r.pdb, num(r.NET_USV), num(r.RIP), num(r.EMP), num(r.DSC),
                                num(r.correction if pd.notna(r.correction) else np.nan),
                                num(r.sens_correction if pd.notna(r.sens_correction) else np.nan),
                                f"\\ensuremath{{{r.dG_uncorrected:.2f}}}",
                                "--" if pd.isna(r.dG_corrected) else f"\\ensuremath{{{r.dG_corrected:.2f}}}"]) + r" \\")
(HERE.parent / "tableS10_rows.tex").write_text("% Generated by analysis/charge_table.py -- do not edit.\n" + "\n".join(rows) + "\n")

m = {}
name = {"TIP3P": "Three", "TIP4P": "Four", "TIP5P": "Five", "TIP7P": "Seven"}
for model, k in name.items():
    s = cor[cor.model == model]
    full = s.correction.notna().all()
    col = "correction" if full else "analytical_only"
    sg = lambda x: f"\\ensuremath{{{x:+.2f}}}"
    m[f"chgMin{k}"] = sg(s[col].min()); m[f"chgMax{k}"] = sg(s[col].max())
    m[f"chgDscMin{k}"] = "--" if not full else sg(s.DSC.min())
    m[f"chgDscMax{k}"] = "--" if not full else sg(s.DSC.max())
    if full:
        corr = np.array(CALC[model], float)
        for _, r in s.iterrows():
            corr[PDB.index(r.pdb)] = r.dG_corrected
        e = corr - EXP
        m[f"chgMue{k}"] = f"{np.abs(e).mean():.2f}"; m[f"chgRmse{k}"] = f"{np.sqrt((e**2).mean()):.2f}"
        m[f"chgBias{k}"] = f"\\ensuremath{{{e.mean():.2f}}}"
sens_shift = (cor.correction - cor.sens_correction).dropna()
m["chgSensMin"], m["chgSensMax"] = f"{sens_shift.min():.2f}", f"{sens_shift.max():.2f}"
other = pd.concat([cor.NET_USV.abs(), cor.RIP.abs(), cor.EMP.abs()])
m["chgOtherMax"] = f"{other.max():.2f}"
g = {}
for d in (161, 257, 353):
    t = pd.read_csv(C / f"rocklin_legs_v2_d{d}_main.tsv", sep="\t")
    t = t[(t.model == "TIP3P") & (t.pdb == "6V1B")].set_index("leg")
    g[d] = t.loc["complex", "total"] - t.loc["solvent", "total"]
alt = pd.read_csv(C / "rocklin_legs_v2_d257_alt.tsv", sep="\t").set_index(["model", "pdb", "leg"])
main = pd.read_csv(C / "rocklin_legs_v2_d257_main.tsv", sep="\t").set_index(["model", "pdb", "leg"])
bind = lambda t, mo, p: t.loc[(mo, p, "complex"), "total"] - t.loc[(mo, p, "solvent"), "total"]
m["chgEpsMax"] = f"{max(abs(bind(alt, mo, p) - bind(main, mo, p)) for mo, p in {(a, b) for a, b, _ in alt.index}):.2f}"
s7 = cor[cor.model == "TIP7P"]
if SHOW_TIP7P_O_APPROX and "correction_O_approx" in s7:
    m["chgApproxMinSeven"] = f"\\ensuremath{{{s7.correction_O_approx.min():+.2f}}}"
    m["chgApproxMaxSeven"] = f"\\ensuremath{{{s7.correction_O_approx.max():+.2f}}}"
m["chgGridSpread"] = f"{(max(g.values()) - min(g.values())):.3f}"
(HERE.parent / "numbers_charge.tex").write_text("% Generated by analysis/charge_table.py -- do not edit.\n"
                                                 + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()) + "\n")
print(open(HERE.parent / "tableS10_rows.tex").read()); print(m)
