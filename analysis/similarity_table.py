"""Table 1 (pairwise ligand Tanimoto similarity) from ligands.tsv.
"""
import csv
from pathlib import Path

import numpy as np
from rdkit import Chem, DataStructs, RDLogger
from rdkit.Chem import rdFingerprintGenerator

from pairwise_ddg import BRD, PDB

RDLogger.DisableLog("rdApp.*")
HERE = Path(__file__).resolve().parent
ORDER_ROWS = ["4ZQL", "5DKH", "5I8G", "5IGL", "5LJ0", "6V1B", "7BL8", "7L9G", "8AG2"]
ORDER_COLS = ["3MXF", "4ZQL", "5DKH", "5I8G", "5IGL", "5LJ0", "6V1B", "7BL8", "7L9G"]


def main():
    with open(HERE / "ligands.tsv") as fh:
        smiles = {r["pdb"]: r["smiles_as_used_for_fingerprints"].strip() for r in csv.DictReader(fh, delimiter="\t")}
    gen = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=2048)
    fps = {p: gen.GetFingerprint(Chem.MolFromSmiles(s)) for p, s in smiles.items()}
    sim = {(a, b): DataStructs.TanimotoSimilarity(fps[a], fps[b]) for a in fps for b in fps}

    tsv_order = ["8AG2", "7L9G", "3MXF", "5I8G", "5LJ0", "6V1B", "7BL8", "4ZQL", "5IGL", "5DKH"]
    with open(HERE / "ligand_similarity.tsv", "w") as fh:
        fh.write("pdb\t" + "\t".join(tsv_order) + "\n")
        for a in tsv_order:
            fh.write(a + "\t" + "\t".join(f"{sim[a, b]:.3f}" for b in tsv_order) + "\n")

    pairs = [(sim[a, b], a, b) for i, a in enumerate(PDB) for b in PDB[i + 1:]]
    vals = np.array([p[0] for p in pairs])
    top = max(pairs)
    top_pair = {top[1], top[2]}
    name = dict(zip(PDB, BRD))
    rows = []
    for r in ORDER_ROWS:
        cells = []
        for c in ORDER_COLS:
            if ORDER_ROWS.index(r) + 1 <= ORDER_COLS.index(c):
                cells.append("")
            else:
                v = f"{sim[r, c]:.3f}"
                cells.append(r"\textbf{" + v + "}" if {r, c} == top_pair else v)
        rows.append(f"    {r} ({name[r]}) & " + " & ".join(cells) + r" \\")
    (HERE.parent / "table1_rows.tex").write_text("% Generated by analysis/similarity_table.py -- do not edit.\n"
                                                + "\n".join(rows) + "\n")
    a, b = sorted(top_pair, key=PDB.index)
    macros = {"simMin": f"{vals.min():.3f}", "simMax": f"{vals.max():.3f}",
              "simMedian": f"{np.median(vals):.3f}", "simMaxPair": f"{a}/{b}", "simNPairs": str(len(vals))}
    (HERE.parent / "numbers_similarity.tex").write_text(
        "% Generated by analysis/similarity_table.py -- do not edit.\n"
        + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print(macros)
    assert vals.max() <= 0.25, "redundancy cutoff violated"


if __name__ == "__main__":
    main()
