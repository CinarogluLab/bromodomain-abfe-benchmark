"""Write every derived number quoted in the Results as LaTeX macros, plus the Table 4 rows.
"""
from pathlib import Path

import numpy as np
from scipy import stats

from legs_analysis import load
from metrics import TDS
from pairwise_ddg import BINS, CALC, EXP, PDB, summarize

HERE = Path(__file__).resolve().parent
NAME = {"TIP3P": "Three", "TIP4P": "Four", "TIP5P": "Five", "TIP7P": "Seven"}
SITES = {"TIP3P": 3, "TIP4P": 4, "TIP5P": 5, "TIP7P": 7}


def num(x, nd=2, sign=False):
    """Number in math mode so that negatives get a true minus sign."""
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return f"\\ensuremath{{{s}}}" if s.startswith(("-", "+")) else s


def main():
    macros, table, s3, s5 = {}, [], [], []
    n = len(EXP)
    for model, values in CALC.items():
        k = NAME[model]
        calc = np.array(values)
        err = calc - EXP
        mue, rmse, bias = np.abs(err).mean(), np.sqrt(np.mean(err**2)), err.mean()
        r = stats.pearsonr(EXP, calc)[0]
        z, se = np.arctanh(r), 1 / np.sqrt(n - 3)
        lo, hi = np.tanh([z - 1.96 * se, z + 1.96 * se])
        tau, p_tau = stats.kendalltau(EXP, calc)
        centered = np.sqrt(np.mean((err - err.mean()) ** 2))
        r_tds, p_tds = stats.pearsonr(err, TDS)
        macros.update({
            f"mue{k}": num(mue), f"rmse{k}": num(rmse), f"bias{k}": num(bias),
            f"r{k}": num(r), f"rlo{k}": num(lo), f"rhi{k}": num(hi),
            f"tau{k}": num(tau), f"taup{k}": f"{p_tau:.2f}" if p_tau >= 0.01 else f"{p_tau:.3f}",
            f"ocrmse{k}": num(centered), f"ocpct{k}": f"{100 * (1 - centered / rmse):.0f}",
            f"rtds{k}": num(r_tds), f"rtdsp{k}": f"{p_tds:.2f}",
        })
        s3.append(f"    {model} & {num(bias)} & {num(rmse)} & {num(centered)} & {macros[f'ocpct{k}']} \\\\")
        table.append(f"    {model} ({SITES[model]}-site) & {num(mue)} & {num(rmse)} & {num(bias)} & "
                     f"{num(r)} [{num(lo)}, {num(hi)}] & {num(tau)} ($p = {macros[f'taup{k}']}$) \\\\")

    spread = np.ptp(np.array(list(CALC.values())), axis=0)
    order = np.argsort(-spread)
    macros.update(spreadMax=num(spread[order[0]]), spreadMaxPdb=PDB[order[0]],
                  spreadSecond=num(spread[order[1]]), spreadSecondPdb=PDB[order[1]])

    legs = load()
    sig = np.array([legs[m, p]["err"] for m in CALC for p in PDB])
    macros.update(sigmaMin=num(sig.min()), sigmaMax=num(sig.max()), sigmaMedian=num(np.median(sig)))

    for label, keep in (("", set(range(10))), ("No", set(range(10)) - {PDB.index("5I8G")})):
        dexp, res = summarize(keep)
        s5.append(r"    \multicolumn{9}{l}{\textit{" + ("all complexes" if not label else "excluding 5I8G")
                  + f" ({len(dexp)} pairs)" + r"}} \\")
        for model, s in res.items():
            s5.append(f"    {model} & {num(s['mue'])} & {num(s['rmse'])} & {num(s['r'])} & {100 * s['within1']:.0f} & "
                      f"{100 * s['sign']:.0f} & " + " & ".join(f"{100 * f:.0f} ({nb})" for nb, f in s["sign_by_bin"]) + r" \\")
            k = NAME[model] + label
            macros.update({f"pwSign{k}": f"{100 * s['sign']:.0f}", f"pwMue{k}": num(s["mue"]),
                           f"pwRmse{k}": num(s["rmse"]), f"pwWithin{k}": f"{100 * s['within1']:.0f}"})
            for (nbin, frac), tag in zip(s["sign_by_bin"], ("Close", "Mid", "Far")):
                macros[f"pwSign{tag}{k}"] = f"{100 * frac:.0f}"
                macros[f"pwN{tag}{label}"] = str(nbin)

    import pandas as pd
    bench = pd.read_csv(HERE / "bench" / "bench_summary.tsv", sep="\t").set_index("model")
    t5 = []
    for model in CALC:
        k, b = NAME[model], bench.loc[model]
        macros.update({f"costDays{k}": f"{b.gpu_days:.1f}", f"costRel{k}": f"{b.relative:.1f}",
                       f"costRelLo{k}": f"{b.rel_min:.1f}", f"costRelHi{k}": f"{b.rel_max:.1f}",
                       f"costNsday{k}": f"{b.complex_nsday:.0f}", f"costAtoms{k}": f"{b.complex_atoms / 1000:.0f}"})
        t5.append(f"    {model} & {SITES[model]} & {b.complex_atoms / 1000:.0f} & {b.complex_nsday:.0f} & "
                  f"{b.ligand_nsday:.0f} & {b.gpu_days:.1f} & {b.relative:.1f} & {macros[f'rmse{k}']} \\\\")
    (HERE.parent / "table5_rows.tex").write_text("\n".join(t5) + "\n")

    from pairwise_ddg import BRD
    prov = pd.read_csv(HERE / "mbar" / "abfe_legs_provenance.tsv", sep="\t")
    prov = set(map(tuple, prov[prov.status != "mbar_reanalysis"][["model", "pdb"]].values))
    t3 = []
    for i, (pdb, brd) in enumerate(zip(PDB, BRD)):
        cells = [num(CALC[m][i]) + (r"$^{b}$" if (m, pdb) in prov else "") for m in CALC]
        t3.append(f"    {pdb} & {brd} & {num(EXP[i])} & " + " & ".join(cells) + r" \\")
    (HERE.parent / "table3_rows.tex").write_text("\n".join(t3) + "\n")

    lines = ["% Generated by analysis/text_numbers.py -- do not edit by hand.\n"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    (HERE.parent / "numbers_generated.tex").write_text("\n".join(lines) + "\n")
    (HERE.parent / "table4_rows.tex").write_text("\n".join(table) + "\n")
    (HERE.parent / "tableS3_rows.tex").write_text("\n".join(s3) + "\n")
    (HERE.parent / "tableS5_rows.tex").write_text("\n".join(s5) + "\n")
    print(f"wrote {len(macros)} macros and table4_rows.tex")
    for k, v in macros.items():
        print(f"  \\{k} = {v}")


if __name__ == "__main__":
    main()
